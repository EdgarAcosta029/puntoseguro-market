-- Base de datos de "PuntoSeguro Market" para SUPABASE (PostgreSQL).
-- (Incluye todo hasta la fase 2: mapa de puntos seguros, pagos con custodia simulada, INE, variantes.)
-- Uso: Supabase > SQL Editor > New query > pega TODO este archivo > Run.
-- Para empezar de cero: ejecuta primero  DROP SCHEMA public CASCADE; CREATE SCHEMA public;  (borra todo)

CREATE TABLE puntos_seguros_ce (      -- lugares públicos y concurridos para entregar (mapa)
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  direccion VARCHAR(250) NOT NULL,
  horario VARCHAR(120) NULL,
  descripcion TEXT NULL,
  lat NUMERIC(9,6) NOT NULL,
  lng NUMERIC(9,6) NOT NULL,
  verificado SMALLINT NOT NULL DEFAULT 0,          -- 1 = la ubicación ya se confirmó en el mapa
  activo SMALLINT NOT NULL DEFAULT 1
);
CREATE TABLE usuarios_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  direccion TEXT NULL,
  punto_entrega TEXT NULL,                         -- punto donde el vendedor entrega sus productos
  punto_entrega_id INT NULL REFERENCES puntos_seguros_ce(id) ON DELETE SET NULL,
  ine_estado VARCHAR(12) NOT NULL DEFAULT 'no',    -- no | verificada
  ine_fecha TIMESTAMPTZ NULL,
  ine_hash VARCHAR(64) NULL UNIQUE,                -- huella de la credencial; nunca se guarda la imagen
  pref_email SMALLINT NOT NULL DEFAULT 1,
  pref_sms SMALLINT NOT NULL DEFAULT 0,
  pref_promo SMALLINT NOT NULL DEFAULT 1,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE direcciones_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuarios_ce(id) ON DELETE CASCADE,
  etiqueta VARCHAR(40) NOT NULL,
  texto VARCHAR(300) NOT NULL,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE categorias_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  padre_id INT NULL REFERENCES categorias_ce(id)
);
CREATE TABLE marcas_ce (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(80) NOT NULL UNIQUE);
CREATE TABLE productos_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  descripcion TEXT NULL,
  emoji VARCHAR(16) NOT NULL DEFAULT '📦',        -- se muestra si el producto no tiene imagen
  color VARCHAR(9) NOT NULL DEFAULT '#9DB7C4',
  categoria_id INT NOT NULL REFERENCES categorias_ce(id),   -- subcategoría (su padre es la categoría principal)
  marca_id INT NOT NULL REFERENCES marcas_ce(id),
  precio NUMERIC(10,2) NOT NULL,
  precio_anterior NUMERIC(10,2) NULL,              -- si tiene valor, el producto está en oferta
  stock INT NOT NULL DEFAULT 0,
  popularidad INT NOT NULL DEFAULT 0,
  es_nuevo SMALLINT NOT NULL DEFAULT 0,
  condicion VARCHAR(12) NOT NULL DEFAULT 'usado' CHECK (condicion IN ('nuevo','seminuevo','usado')),
  opciones JSONB NOT NULL DEFAULT '{}'::jsonb,     -- {"Color":["Negro","Azul"],"Talla":["M","L"]}
  vendedor_id INT NULL REFERENCES usuarios_ce(id) ON DELETE SET NULL,   -- NULL = vende la tienda
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE imagenes_producto_ce (   -- solo guarda la URL; el archivo vive en Supabase Storage (bucket "productos")
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id INT NOT NULL REFERENCES productos_ce(id) ON DELETE CASCADE,
  ruta VARCHAR(400) NOT NULL,
  orden INT NOT NULL DEFAULT 0
);
CREATE TABLE resenas_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id INT NOT NULL REFERENCES productos_ce(id) ON DELETE CASCADE,
  usuario_id INT NULL REFERENCES usuarios_ce(id) ON DELETE SET NULL,
  autor VARCHAR(100) NOT NULL,
  calificacion SMALLINT NOT NULL CHECK (calificacion BETWEEN 1 AND 5),
  comentario TEXT NOT NULL,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE carritos_guardados_ce (
  usuario_id INT PRIMARY KEY REFERENCES usuarios_ce(id) ON DELETE CASCADE,
  contenido JSONB NOT NULL
);
CREATE TABLE lista_deseos_ce (
  usuario_id INT NOT NULL REFERENCES usuarios_ce(id) ON DELETE CASCADE,
  producto_id INT NOT NULL REFERENCES productos_ce(id) ON DELETE CASCADE,
  PRIMARY KEY (usuario_id, producto_id)
);
CREATE TABLE codigos_descuento_ce (
  codigo VARCHAR(40) PRIMARY KEY,
  tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('porcentaje')),
  valor INT NOT NULL DEFAULT 0,
  activo SMALLINT NOT NULL DEFAULT 1
);
CREATE TABLE pedidos_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  usuario_id INT NULL REFERENCES usuarios_ce(id) ON DELETE SET NULL,   -- NULL = compra como invitado
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL,
  vendedor_id INT NULL REFERENCES usuarios_ce(id) ON DELETE SET NULL,  -- cada pedido es de un solo vendedor (NULL = plataforma)
  entrega_modo VARCHAR(10) NOT NULL DEFAULT 'chat',                    -- vendedor | chat | tienda
  punto_acordado TEXT NULL,
  punto_propuesto TEXT NULL,
  propuesto_por INT NULL,
  pago VARCHAR(20) NOT NULL,
  subtotal NUMERIC(10,2) NOT NULL,
  descuento NUMERIC(10,2) NOT NULL DEFAULT 0,
  envio NUMERIC(10,2) NOT NULL DEFAULT 0,
  total NUMERIC(10,2) NOT NULL,
  estado SMALLINT NOT NULL DEFAULT 0,               -- 0 pedido confirmado, 1 punto de entrega acordado, 2 entregado, 3 cancelado
  pago_estado VARCHAR(12) NOT NULL DEFAULT 'retenido',   -- pendiente | retenido | liberado | reembolsado | cancelado
  pago_detalle VARCHAR(80) NULL,
  telefono VARCHAR(20) NULL,                        -- celular del comprador (obligatorio si compra como invitado)
  codigo_seguimiento VARCHAR(12) NULL,              -- código para que un invitado consulte y confirme su pedido
  comprador_confirmo SMALLINT NOT NULL DEFAULT 0,   -- el comprador confirmó que recibió
  vendedor_confirmo SMALLINT NOT NULL DEFAULT 0,    -- el vendedor confirmó que entregó
  pago_ref VARCHAR(40) NULL,                        -- CLABE (SPEI) o referencia (efectivo)
  pago_vence TIMESTAMPTZ NULL,
  punto_id INT NULL REFERENCES puntos_seguros_ce(id) ON DELETE SET NULL,
  punto_propuesto_id INT NULL REFERENCES puntos_seguros_ce(id) ON DELETE SET NULL,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE mensajes_pedido_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INT NOT NULL REFERENCES pedidos_ce(id) ON DELETE CASCADE,
  usuario_id INT NOT NULL REFERENCES usuarios_ce(id) ON DELETE CASCADE,
  texto VARCHAR(500) NOT NULL,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE pedido_items_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INT NOT NULL REFERENCES pedidos_ce(id) ON DELETE CASCADE,
  producto_id INT NOT NULL REFERENCES productos_ce(id),
  nombre VARCHAR(150) NOT NULL,
  precio NUMERIC(10,2) NOT NULL,
  cantidad INT NOT NULL,
  variante VARCHAR(160) NULL
);
CREATE TABLE mensajes_contacto_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL, mensaje TEXT NOT NULL,
  leido SMALLINT NOT NULL DEFAULT 0,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE suscriptores_newsletter_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(150) NOT NULL UNIQUE,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);

