CREATE TABLE IF NOT EXISTS puntos_seguros_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  direccion VARCHAR(250) NOT NULL,
  horario VARCHAR(120) NULL,
  descripcion TEXT NULL,
  lat NUMERIC(9,6) NOT NULL,
  lng NUMERIC(9,6) NOT NULL,
  verificado SMALLINT NOT NULL DEFAULT 0,          -- 1 = la ubicación ya se confirmó en el mapa
  activo SMALLINT NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS direcciones_ce (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuarios_ce(id) ON DELETE CASCADE,
  etiqueta VARCHAR(40) NOT NULL,
  texto VARCHAR(300) NOT NULL,
  creado TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE usuarios_ce
  ADD COLUMN IF NOT EXISTS punto_entrega_id INT NULL REFERENCES puntos_seguros_ce(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS ine_estado VARCHAR(12) NOT NULL DEFAULT 'no',   -- no | verificada
  ADD COLUMN IF NOT EXISTS ine_fecha TIMESTAMPTZ NULL,
  ADD COLUMN IF NOT EXISTS ine_hash VARCHAR(64) NULL UNIQUE;                -- huella de la credencial; nunca se guarda la imagen

ALTER TABLE productos_ce
  ADD COLUMN IF NOT EXISTS condicion VARCHAR(12) NOT NULL DEFAULT 'usado' CHECK (condicion IN ('nuevo','seminuevo','usado')),
  ADD COLUMN IF NOT EXISTS opciones JSONB NOT NULL DEFAULT '{}'::jsonb;     -- {"Color":["Negro","Azul"],"Talla":["M","L"]}

ALTER TABLE pedidos_ce
  ADD COLUMN IF NOT EXISTS pago_estado VARCHAR(12) NOT NULL DEFAULT 'retenido',  -- pendiente | retenido | liberado | reembolsado | cancelado
  ADD COLUMN IF NOT EXISTS pago_detalle VARCHAR(80) NULL,
  ADD COLUMN IF NOT EXISTS pago_ref VARCHAR(40) NULL,                            -- CLABE (SPEI) o referencia (efectivo)
  ADD COLUMN IF NOT EXISTS pago_vence TIMESTAMPTZ NULL,
  ADD COLUMN IF NOT EXISTS punto_id INT NULL REFERENCES puntos_seguros_ce(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS punto_propuesto_id INT NULL REFERENCES puntos_seguros_ce(id) ON DELETE SET NULL;
-- estado: 0 confirmado, 1 punto acordado, 2 entregado, 3 cancelado
UPDATE pedidos_ce SET pago_estado = 'liberado' WHERE estado = 2 AND pago_estado = 'retenido';

ALTER TABLE pedido_items_ce ADD COLUMN IF NOT EXISTS variante VARCHAR(160) NULL;
ALTER TABLE mensajes_contacto_ce ADD COLUMN IF NOT EXISTS leido SMALLINT NOT NULL DEFAULT 0;

ALTER TABLE puntos_seguros_ce ENABLE ROW LEVEL SECURITY;
ALTER TABLE direcciones_ce ENABLE ROW LEVEL SECURITY;
